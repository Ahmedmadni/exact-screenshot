import type { AssetRecord, BrandKit, Presentation, Slide, ThemeRecord } from "@/lib/types";

const now = Date.now();
const iso = (daysAgo: number) => new Date(now - daysAgo * 86_400_000).toISOString();

function slide(
  presentationId: string,
  index: number,
  data: Omit<Slide, "id" | "presentationId" | "slideNumber" | "sortOrder" | "elements" | "createdAt" | "updatedAt">,
): Slide {
  return {
    id: `${presentationId}-s${index + 1}`,
    presentationId,
    slideNumber: index + 1,
    sortOrder: index,
    elements: [],
    createdAt: iso(10),
    updatedAt: iso(1),
    ...data,
  };
}

function deck(
  id: string,
  base: Omit<Presentation, "id" | "slides" | "userId">,
  slides: Array<Parameters<typeof slide>[2]>,
): Presentation {
  return {
    id,
    userId: "local-user",
    ...base,
    slides: slides.map((s, i) => slide(id, i, s)),
  };
}

